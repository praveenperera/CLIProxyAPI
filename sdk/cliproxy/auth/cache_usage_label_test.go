const claudeCodePayload = `{
  "system": [{"type": "text", "text": "You are Claude Code.\n# Environment\n - Primary working directory: /Users/me/code/CLIProxyAPI\n - Is a git repository: true"}],
  "messages": [
    {"role": "user", "content": [
      {"type": "text", "text": "<system-reminder>\nCLAUDE.md contents\n</system-reminder>"},
      {"type": "text", "text": "<system-reminder>\ngit status\n</system-reminder>"},
      {"type": "text", "text": "why is traffic   going to\n@avencera?"}
    ]},
    {"role": "assistant", "content": [{"type": "text", "text": "Checking."}]},
    {"role": "user", "content": [{"type": "text", "text": "a later turn"}]}
  ]
}`

func TestExtractSessionLabel(t *testing.T) {
	cases := []struct {
		name, payload, title, project string
	}{
		{"claude code", claudeCodePayload, "why is traffic going to @avencera?", "CLIProxyAPI"},
		{
			"codex responses",
			`{"input": [
			  {"role": "user", "content": [{"type": "input_text", "text": "<environment_context>\n<cwd>/home/me/code/cudakit</cwd>\n</environment_context>"}]},
			  {"role": "user", "content": [{"type": "input_text", "text": "port the kernel"}]}
			]}`,
			"port the kernel", "cudakit",
		},
		{"chat string content", `{"messages": [{"role": "system", "content": "be brief"}, {"role": "user", "content": "hello <system-reminder>x</system-reminder>there"}]}`, "hello there", ""},
		{
			"codex agents.md turn",
			`{"input": [
			  {"role": "user", "content": [{"type": "input_text", "text": "# AGENTS.md instructions for /home/me/code/cudakit\n\n<INSTRUCTIONS>\nbe terse\n</INSTRUCTIONS>"}]},
			  {"role": "user", "content": [{"type": "input_text", "text": "fix the build"}]}
			]}`,
			"fix the build", "",
		},
		{
			"claude code slash command",
			`{"messages": [
			  {"role": "user", "content": "<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args></command-args>"},
			  {"role": "user", "content": "Caveat: The messages below were generated by the user while running local commands."},
			  {"role": "user", "content": "check the diff"}
			]}`,
			"check the diff", "",
		},
		{
			"quoted marker in a compacted summary",
			`{"messages": [{"role": "user", "content": "Continued session. Note: Primary working directory: … appears in the system prompt"}],
			  "system": [{"type": "text", "text": " - Primary working directory: /Users/me/code/CLIProxyAPI\n"}]}`,
			"Continued session. Note: Primary working directory: … appears in the system prompt", "CLIProxyAPI",
		},
		{"no user prompt", `{"messages": [{"role": "user", "content": "<system-reminder>only context</system-reminder>"}]}`, "", ""},
	}
	for _, tc := range cases {
		title, project := extractSessionLabel([]byte(tc.payload))
		if title != tc.title || project != tc.project {
			t.Errorf("%s: got (%q, %q), want (%q, %q)", tc.name, title, project, tc.title, tc.project)
		}
	}

	long, _ := extractSessionLabel([]byte(`{"messages": [{"role": "user", "content": "` + strings.Repeat("word ", 60) + `"}]}`))
	if n := len([]rune(long)); n != cacheUsageTitleMaxRunes || !strings.HasSuffix(long, "…") {
		t.Errorf("long title has %d runes (%q), want %d ending in an ellipsis", n, long, cacheUsageTitleMaxRunes)
	}
}

func TestCacheUsageSessionLabelLifecycle(t *testing.T) {
	m, _, cfg, _, ids := affinityFixture(t)
	now := time.Now()
	ctx := logging.WithClientRequestMetadata(context.Background(), logging.ClientRequestMetadata{SessionID: "claude:s1"})

	// the label is read before the request finishes and creates the session
	m.noteCacheUsageLabel(ctx, requestPayload(exec.Request{}, exec.Options{OriginalRequest: []byte(claudeCodePayload)}))
	// later turns, or a compacted history, never rename the session
	m.noteCacheUsageLabel(ctx, []byte(`{"messages": [{"role": "user", "content": "This session is being continued"}]}`))
	m.CacheUsagePlugin().HandleUsage(context.Background(), cacheUsageRecord(ids[0], "claude:s1", now, 10, 90, 0))

	// a label whose request never finished is dropped once the pending window passes
	orphanCtx := logging.WithClientRequestMetadata(context.Background(), logging.ClientRequestMetadata{SessionID: "claude:orphan"})
	m.noteCacheUsageLabel(orphanCtx, []byte(`{"messages": [{"role": "user", "content": "never answered"}]}`))

	query := CacheUsageQuery{Since: now.Add(-time.Hour), Until: now.Add(time.Minute)}
	sessions := m.CacheUsage(query).Sessions
	if len(sessions) != 1 || sessions[0].Title != "why is traffic going to @avencera?" || sessions[0].Project != "CLIProxyAPI" {
		t.Fatalf("sessions = %+v", sessions)
	}

	m.cacheUsage.close()
	restarted := NewManager(nil, nil, nil)
	restarted.cacheUsage.now = func() time.Time { return now.Add(2 * cacheUsageLabelPending) }
	restarted.cacheUsage.persistTo(cfg.Routing.QuotaAwareChatAffinity.StateDir)
	again := restarted.CacheUsage(query).Sessions
	if len(again) != 1 || again[0].Title != sessions[0].Title {
		t.Fatalf("after restart sessions = %+v", again)
	}
	if restarted.cacheUsage.hasLabel("claude:orphan") {
		t.Fatal("orphan label survived past the pending window")
	}
}

func TestCacheUsageLabelsStopGrowingAtTheCap(t *testing.T) {
	now := time.Unix(1_800_000_000, 0)
	c := newCacheUsage(func() time.Time { return now })
	// requests that fail before recording usage leave labels with no session
	for i := range cacheUsageMaxLabels {
		c.noteLabel("failed-"+strconv.Itoa(i), "title", "project")
	}
	c.noteLabel("new-session", "kept later", "project")
	if c.hasLabel("new-session") || len(c.labels) != cacheUsageMaxLabels {
		t.Fatalf("labels = %d, new session labeled %v", len(c.labels), c.hasLabel("new-session"))
	}

	// once the pending labels age out, a new session is named again
	now = now.Add(cacheUsageLabelPending + time.Minute)
	c.noteLabel("new-session", "kept later", "project")
	if !c.hasLabel("new-session") || len(c.labels) != 1 {
		t.Fatalf("labels = %d after the pending window", len(c.labels))
	}
}
